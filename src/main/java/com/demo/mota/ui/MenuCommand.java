package com.demo.mota.ui;

/**
 * 菜单内的抽象操作。UI 层负责把具体按键映射成这里的语义，
 * 菜单状态机只认语义、不认按键。
 *
 * <p>各菜单只响应自己用得上的操作，其余忽略（例如敌物资料不认 {@link #LEFT} / {@link #RIGHT}）。
 */
public enum MenuCommand {
    /** 上移选择 */
    UP,
    /** 下移选择 */
    DOWN,
    /** 左移选择（技能组合的回合格、装备槽网格） */
    LEFT,
    /** 右移选择 */
    RIGHT,
    /** 确认（回车 / 空格）：进入下一层内容 / 执行当前操作 */
    CONFIRM,
    /** 清除当前格（技能组合中把某回合清回普攻） */
    CLEAR,
    /** 返回上一层内容，已在最外层时关闭菜单 */
    BACK,
    /** 直接关闭菜单 */
    CLOSE
}
